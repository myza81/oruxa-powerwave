// real-browser coverage. See docs/development/BROWSER_SMOKE_TEST.md for
// the general foundation this extends, and the Playback architecture
// audit / Slice 1 report for why real timer/rAF/Plotly-overlay behavior
// needs a real browser rather than a source-text assertion
// (backend/tests/test_frontend_playback.py covers the structural/static
// invariants that DON'T need one).
//
// Owner product decision (2026-09-12): Playback CONTROLS (Restart/Play/
// Speed/seek) are mounted on Analysis pages only (Phasor today, via
// wwPhasorMountPlaybackControls()) -- the raw Waveform Time Group toolbar
// no longer mounts them (see DECISIONS.md DEC-085's own "Update
// (2026-09-12)" section). This file previously drove every control
// directly from a Waveform Time Group canvas's own `.ww-tg-playback-*`
// elements; it now drives the SAME shared, unchanged engine
// (wwPlayback/wwPlaybackState()/wwPlaybackPlay() etc.) through Phasor's
// own mounted control surface instead -- the engine itself, and every
// invariant these tests guard, is unchanged; only the UI entry point
// used to exercise it changed. The Waveform Time Group canvas's own
// PASSIVE Playback Cursor overlay (`.ww-tg-playback-cursor-overlay`) is
// explicitly preserved (it is a readout of the shared clock, not a
// control) and is still asserted directly against the Waveform canvas
// below.
//
// Fixture: synth_playback(.cfg/.dat) / synth_playback_b(.cfg/.dat) --
// deterministic, committed COMTRADE fixtures generated by
// backend/tests/perf/synthetic_comtrade.py (the SAME generator the F2
