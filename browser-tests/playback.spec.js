// Displays a given source's first analog channel on the Waveform page --
// this is what actually forms a real Time Group (a Playback/Phasor
// concept driven entirely off DISPLAYED channels, never upload alone).
// Assumes the Recordings page is already showing `sourceId`'s own row.
async function displayFirstAnalogChannel(page, sourceId) {
  await page.locator(`#recordingsTableBody tr[data-source-id="${sourceId}"]`).click();
  await expect(page.locator("#wwWorkspaceLoading")).toBeHidden();
  const details = page.locator(`#channelGroups details.source-recording[data-source-id="${sourceId}"]`);
  await expect(details).toBeVisible();
  if (!(await details.evaluate((el) => el.open))) await details.locator("> summary").click();
  const channelRow = page
    .locator(`#channelGroups tr.channel-row--toggle[data-channel-kind="analog"][data-source-id="${sourceId}"]`)
    .first();
  await expect(channelRow).toBeVisible();
  await channelRow.click();
  await expect(channelRow).toHaveAttribute("aria-pressed", "true");
  await expect(page.locator(".ww-chart .plotly").first()).toBeVisible();
}

// A minimal, single-member Engineering Context (Va only, from the
// fixture's own bare-role `V0_R` channel) -- Playback-engine coverage
// doesn't need a full six-role bay, just ONE resolvable role so Phasor
// can claim the source's own Time Group and mount real Playback controls
// against it (a partial bay is a normal, fully-supported result -- see
// PHASOR_ANALYSIS.md).
async function createSinglePhaseContext(page, workspaceId, sourceId, displayName) {
  const response = await page.request.post(
    `${BACKEND_URL}/api/v1/workspaces/${encodeURIComponent(workspaceId)}/engineering-contexts`,
    {
      data: {
        display_name: displayName,
        status: "manual",
        members: [
          {
            channel_ref: { kind: "source", source_id: sourceId, channel_name: "V0_R" },
            phase: "A",
            phase_source: "engineer_confirmed",
          },
        ],
      },
    }
  );
  expect(response.ok()).toBeTruthy();
  return response.json();
}

// Full setup: upload a fixture, display its first channel (forms the real
// Time Group and gives access to the Waveform canvas's own passive
// Playback Cursor overlay), create a single-phase Engineering Context
// against it, then open Analysis -> Phasor and select that context so its
// own Playback ribbon mounts. Returns the Waveform canvas locator (for
// `.ww-tg-playback-cursor-overlay` assertions) and the Phasor Playback
// mount locator (for the actual Restart/Play/Speed/seek controls).
async function setupPhasorPlayback(page, stem, displayName) {
  await uploadFixture(page, stem);
  const row = page.locator("#recordingsTableBody tr[data-source-id]").last();
  await expect(row).toBeVisible();
  const sourceId = await row.getAttribute("data-source-id");
  const workspaceId = await page.evaluate(() => localStorage.getItem("powerwave.workspaceId"));

  await displayFirstAnalogChannel(page, sourceId);
  const canvas = page.locator("#wwTimeGroupCanvases .ww-time-group-canvas").first();
  await expect(canvas).toBeVisible();
  // Playback controls are Analysis-only now -- confirm the removal
  // invariant holds for every caller of this setup, not just a dedicated
  // test (belt-and-braces; the dedicated test below is still the primary
  // documentation of this invariant).
  await expect(canvas.locator(".ww-tg-playback-play-btn")).toHaveCount(0);

  const context = await createSinglePhaseContext(page, workspaceId, sourceId, displayName);

  await page.locator("#mainNavAnalysisBtn").click();
  await expect(page.locator("#pageAnalysis")).toBeVisible();
  await expect(page.locator(`#wwPhasorContextSelect option[value="${context.id}"]`)).toHaveCount(1);
  await page.locator("#wwPhasorContextSelect").selectOption(context.id);

  const mount = page.locator("#wwPhasorPlaybackMount");
  await expect(mount.locator(".ww-tg-playback-play-btn")).toBeVisible();

  return { canvas, mount, sourceId, workspaceId, contextId: context.id };
}

