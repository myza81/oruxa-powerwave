"""Oscillation Analysis -- engineer-facing component summary (DEC-183 [APPROVED]; presentation layer over DEC-171..182).

One compact summary per interpreted component: a few key fields, an evidence-status strip and ONE deterministic engineering conclusion.

**This module computes nothing about the signal.** It only reads the structured results that already exist for the component -- the cross-signal
grouping (DEC-178), the damping of its members (DEC-177), the interpretation (DEC-179 / DEC-182) and, when they were computed, its mode shape
(DEC-180) and coherence (DEC-181) -- and arranges them. No spectrum, spectrogram, damping fit, phase or coherence is evaluated, nothing is
classified, and nothing is generated by a model: the wording is assembled from fixed phrases and the structured values (tests exercise every
branch). The detailed sections remain the authoritative record.

Hard rules (DEC-183).

* Evidence that is unavailable for this event (a refused mode shape / coherence on a short event) or not applicable (a single-signal component)
  is reported as such. It is never worded or marked as a failure or an error, and it never lowers anything.
* Single-signal components say so; mode shape and coherence are *not applicable* to them.
* Shared provenance never strengthens the spatial evidence: the distinct-measurement count is the one already computed by the grouping.
* No severity, risk or criticality wording; a growing oscillation is called growing, nothing more. "Dominant" is never used.
* Anti-phase never proves inter-area and near-in-phase never proves local; the DEC-182 strength vocabulary is reused unchanged
  (Possible / Consistent with / Supported (provisional) / subtype unresolved).

Pure Python, a handful of comparisons per component.
"""

from __future__ import annotations

from app.domain import oscillation_classification as oc
from app.domain import oscillation_integration as oi

AVAILABLE = "available"
UNAVAILABLE = "unavailable"
NOT_APPLICABLE = "not_applicable"
CAUTION = "caution"
#: Short visible words (never "failed" / "error": an unavailable layer is a valid result).
STATUS_LABELS = {
    AVAILABLE: "Available",
    UNAVAILABLE: "Unavailable for this event",
    NOT_APPLICABLE: "Not applicable",
    CAUTION: "Caution",
}

#: Refusals caused by too little shared active time (they get the one concise "interval is too short" explanation).
_SHORT_INTERVAL_CODES = frozenset({"too_few_cycles", "insufficient_segments", "no_common_activity", "too_few_samples"})
_WORDS = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine", 10: "ten"}
_BEHAVIOUR_ADJECTIVE = {
    oc.BEHAVIOUR_RINGDOWN: "decaying", oc.BEHAVIOUR_DECAYING: "decaying", oc.BEHAVIOUR_SUSTAINED: "sustained",
    oc.BEHAVIOUR_GROWING: "growing", oc.BEHAVIOUR_INTERMITTENT: "intermittent",
}
_LEVEL_WORDS = {oi.COHERENCE_CLEAR: "clearly above", oi.COHERENCE_MARGINAL: "only marginally above", oi.COHERENCE_BELOW: "not above"}


def _num(value: float, digits: int = 3) -> str:
    return f"{value:.{digits}g}"


def _hz(value: float) -> str:
    return f"{round(value, 2):g}"


def _word(count: int) -> str:
    return _WORDS.get(count, str(count))


def _seconds(value: float) -> str:
    return f"{value:.0f} s" if value >= 10 else f"{value:.1f} s"


def _plural(count: int, noun: str) -> str:
    return f"{count} {noun}" + ("" if count == 1 else "s")


def _after_label(message: str, label: str) -> str:
    """The backend's refusal text is reused verbatim; a leading "<Layer> unavailable —" label is dropped only because the strip already says it."""
    prefix = f"{label} unavailable — "
    return message[len(prefix):] if message.startswith(prefix) else message


def _entry(code: str, label: str, status: str, detail: str, *, show_detail: bool = True) -> dict:
    return {"code": code, "label": label, "status": status, "status_label": STATUS_LABELS[status], "detail": detail, "show_detail": show_detail}


# ---------------------------------------------------------------- evidence layers
def _spectrum_layer(component: dict) -> dict:
    return _entry("spectrum", "Spectrum", AVAILABLE,
                  f"Welch spectral peak near {_hz(component['representative_frequency_hz'])} Hz, up to {_num(component['max_prominence_db'])} dB above its base.",
                  show_detail=False)


def _time_frequency_layer(component: dict) -> dict:
    members = component["members"]
    located = sum(1 for m in members if (m.get("temporal") or {}).get("status") == "ok")
    if located:
        return _entry("time_frequency", "Time-frequency", AVAILABLE,
                      f"Time-localised activity found in {located} of {_plural(len(members), 'signal')}.", show_detail=False)
    return _entry("time_frequency", "Time-frequency", UNAVAILABLE, "No time-localised activity could be established for this component.", show_detail=False)


def _cross_signal_layer(component: dict) -> tuple[dict, dict]:
    signals, distinct, recordings = component["signal_count"], component["distinct_measurement_count"], component["recording_count"]
    temporal = (component.get("evidence") or {}).get("temporal") or {}
    overlap = temporal.get("overlap_s") or 0.0
    facts = {"signals": signals, "recordings": recordings, "distinct_measurements": distinct, "overlap_s": overlap}
    if signals < 2:
        return _entry("cross_signal", "Cross-signal", NOT_APPLICABLE,
                      "Observed in one signal only; cross-signal modal evidence is not applicable."), facts
    text = f"Observed in {_plural(signals, 'signal')} across {_plural(recordings, 'recording')}"
    if distinct < signals:
        text += f", sharing only {_plural(distinct, 'distinct measurement')}"
    text += f"; shared activity overlaps for {_seconds(overlap)}." if overlap > 0 else "; the active intervals do not overlap."
    codes = {w["code"] for w in component["warnings"]}
    status = CAUTION if codes & {"derived_from_same_source", "no_temporal_overlap"} else AVAILABLE
    return _entry("cross_signal", "Cross-signal", status, text), facts


def _damping_layer(component: dict) -> tuple[dict, dict]:
    members = component["members"]
    available = [m for m in members if (m.get("damping") or {}).get("status") == "available"]
    facts = {"available_members": len(available), "members": len(members), "behaviours": [], "ratio_reported": False}
    if not available:
        reason = next(((m.get("damping") or {}).get("message") for m in members if (m.get("damping") or {}).get("message")), None)
        detail = "Unavailable — " + (reason[:1].lower() + reason[1:] if reason else "no valid ringdown estimate for this component.")
        return _entry("damping", "Damping", UNAVAILABLE, detail), facts
    behaviours = sorted({m["damping"]["behaviour"] for m in available})
    facts["behaviours"] = behaviours
    rates = [m["damping"]["decay_rate_per_s"] for m in available if m["damping"].get("decay_rate_per_s") is not None]
    partial = f" ({len(available)} of {_plural(len(members), 'member')} had a valid estimate)" if len(available) < len(members) else ""
    if len(behaviours) > 1:
        parts = ", ".join(f"{m['label']} {m['damping']['behaviour'].replace('_', ' ')}" for m in available)
        return _entry("damping", "Damping", CAUTION, f"Damping behaviour differs between signals ({parts}); it is reported, not averaged."), facts
    behaviour = behaviours[0]
    # Several members: say how many. One valid member among several is named, never presented as the whole component.
    subject = f"{len(available)} members" if len(available) > 1 else (available[0]["label"] if len(members) > 1 else None)

    def head(word: str) -> str:
        if subject is None:
            return word.capitalize()
        return f"{subject} {word}" if len(available) > 1 else f"{word.capitalize()} in {subject} only"
    span = (lambda xs, d: _num(min(xs), d) if min(xs) == max(xs) else f"{_num(min(xs), d)}–{_num(max(xs), d)}")
    if behaviour == "decaying":
        alpha = span(rates, 3) if rates else None
        ratios = [m["damping"]["damping_ratio"] for m in available]
        ratio = span([r * 100.0 for r in ratios], 2) + "%" if ratios and all(r is not None for r in ratios) else None
        facts["ratio_reported"] = ratio is not None
        tau = f", τ = {_num(1.0 / rates[0], 3)} s" if len(rates) == 1 and rates[0] and rates[0] > 0 else ""
        if subject is None:
            tail = f"α = {alpha} s⁻¹{tau}" if alpha else ""
            text = f"{ratio} ({tail})" if ratio and alpha else (f"Decaying, {tail}; damping ratio not reported" if alpha else "Decaying")
        else:
            text = head("decaying") + (f"; α = {alpha} s⁻¹" if alpha else "") + (f"; damping ratio {ratio}" if ratio else "") + partial
        return _entry("damping", "Damping", AVAILABLE, text), facts
    if behaviour == "growing":
        growth = span([abs(r) for r in rates], 3) if rates else None
        text = head("growing") + (f"; growth rate {growth} s⁻¹" if growth else "") + "; no damping ratio is reported" + partial
        return _entry("damping", "Damping", AVAILABLE, text), facts
    text = head("approximately sustained") + "; no damping ratio is reported" + partial
    return _entry("damping", "Damping", AVAILABLE, text), facts


def _mode_shape_layer(component: dict, integrated: bool, shape: dict | None) -> tuple[dict, dict]:
    facts: dict = {"pattern": None, "reason_codes": [], "chosen": None, "computed": integrated and shape is not None}
    if component["signal_count"] < 2:
        return _entry("mode_shape", "Mode shape", NOT_APPLICABLE, "Needs the component in two or more signals; it is observed in one."), facts
    if not integrated or shape is None:
        return _entry("mode_shape", "Mode shape", UNAVAILABLE, "Not computed for this comparison."), facts
    found = oi.mode_shape_facts(shape)
    chosen = found["chosen"]
    facts["reason_codes"] = [g.get("reason_code") for g in found["unavailable"] if g.get("reason_code")]
    if chosen is not None:
        group, pattern = chosen["group"], chosen["pattern"]
        facts["pattern"], facts["chosen"] = pattern["code"], chosen
        reference = group["reference"]["label"]
        unit = group.get("unit") or group["quantity_type"]
        across = f"across {group['distinct_measurement_count']} distinct {unit} measurements"
        if chosen["unstable"] or pattern["code"] == "unstable":
            facts["pattern"] = "unstable"
            return _entry("mode_shape", "Mode shape", CAUTION,
                          f"The relative phase against {reference} is not stable across the common interval; no phase pattern is relied on."), facts
        angles = [abs(m["phase_deg"]) for m in chosen["independents"] if m.get("phase_deg") is not None]
        stable = all((m.get("phase_stability") or {}).get("status") == "stable" for m in chosen["independents"])
        listed = ", ".join(f"~{a:.0f}°" for a in angles)
        if pattern["code"] == "in_phase":
            text = f"Approximately in phase ({listed} from {reference}) {across}."
        else:
            kind = "phase separation" if len(angles) == 1 else "phase separations"
            text = f"{'Stable ' if stable else 'Not fully assessed: '}{listed} {kind} from {reference} {across} ({pattern['label'].lower()})."
        return _entry("mode_shape", "Mode shape", AVAILABLE, text), facts
    if found["provenance_only"]:
        facts["pattern"] = "shared_provenance"
        return _entry("mode_shape", "Mode shape", UNAVAILABLE,
                      "Relative phase exists only between signals that share one source measurement; copies of one measurement are not spatial evidence."), facts
    first = found["unavailable"][0] if found["unavailable"] else None
    detail = f"Unavailable — {first['message']}" if first and first.get("message") else "Unavailable — no comparable group of signals was available."
    return _entry("mode_shape", "Mode shape", UNAVAILABLE, detail), facts


def _coherence_layer(component: dict, integrated: bool, coherence: dict | None, chosen: dict | None) -> tuple[dict, dict]:
    facts: dict = {"level": None, "reason_codes": [], "same_variable": 0, "computed": integrated and coherence is not None}
    if component["signal_count"] < 2:
        return _entry("coherence", "Coherence", NOT_APPLICABLE, "Needs the component in two or more signals; it is observed in one."), facts
    if not integrated or coherence is None:
        return _entry("coherence", "Coherence", UNAVAILABLE, "Not computed for this comparison."), facts
    found = oi.coherence_facts(coherence, chosen)
    facts["reason_codes"] = [p.get("reason_code") for p in found["refused"] if p.get("reason_code")]
    facts["same_variable"] = len(found["same"])
    if found["same"]:
        levels = [(p, oi.coherence_level(p)) for p in found["same"]]
        pair, level = min(levels, key=lambda pl: oi.LEVEL_ORDER[pl[1]["level"]])
        facts["level"] = level["level"]
        frequency = _hz(pair["coherence_frequency_hz"])
        scope = "same-variable" if len(levels) == 1 else f"weakest of {len(levels)} same-variable pairs"
        if level["level"] == oi.COHERENCE_UNKNOWN:
            return _entry("coherence", "Coherence", AVAILABLE, f"{pair['coherence']:.2f} at {frequency} Hz ({scope})."), facts
        text = (f"{pair['coherence']:.2f} at {frequency} Hz, {_LEVEL_WORDS[level['level']]} the {level['chance_level']:.2f} 95% null threshold ({scope}).")
        return _entry("coherence", "Coherence", AVAILABLE if level["level"] == oi.COHERENCE_CLEAR else CAUTION, text), facts
    if found["cross"]:
        best = max(found["cross"], key=lambda p: p["coherence"])
        return _entry("coherence", "Coherence", AVAILABLE,
                      f"Cross-variable coherence {best['coherence']:.2f} at {_hz(best['coherence_frequency_hz'])} Hz supports a common dynamic relationship; "
                      "it is not a mode-shape relationship."), facts
    if found["refused"]:
        return _entry("coherence", "Coherence", UNAVAILABLE, f"Unavailable — {_after_label(found['refused'][0]['message'], 'Coherence')}"), facts
    return _entry("coherence", "Coherence", UNAVAILABLE,
                  "Coherence between signals that share one source measurement is not used as evidence."), facts


# ---------------------------------------------------------------- measurement wording
def _units(component: dict, units_by_index: dict[int, str | None]) -> str | None:
    units = {units_by_index.get(m["signal_index"]) for m in component["members"]}
    return units.pop() if len(units) == 1 and None not in units else None


def _observed(component: dict, unit: str | None) -> str:
    signals, distinct = component["signal_count"], component["distinct_measurement_count"]
    noun = f"{unit} measurement" if unit else "measurement"
    if signals == 1:
        return f"one {noun}"
    if distinct < signals:
        return f"{signals} signals that derive from only {_plural(distinct, 'distinct ' + noun)}"
    return f"{distinct} distinct {noun}s"


# ---------------------------------------------------------------- the conclusion
def _lead(component: dict, interpretation: dict, unit: str | None) -> list[str]:
    frequency = _hz(component["representative_frequency_hz"])
    behaviour = interpretation["behaviour_classification"]["code"]
    adjective = _BEHAVIOUR_ADJECTIVE.get(behaviour, "")
    type_code, level = interpretation["probable_type"]["code"], interpretation["classification_level"]
    single = component["signal_count"] == 1
    where = f"{'is detected in' if single else 'is observed in'} {_observed(component, unit)}"
    higher = any(d["code"] == oc.DESCRIPTOR_HIGHER_FREQUENCY for d in interpretation.get("descriptors", [])) if type_code == oc.TYPE_UNRESOLVED else False
    if higher:
        sentences = [f"Higher-frequency oscillatory component detected at ~{frequency} Hz, {'detected' if single else 'observed'} in {_observed(component, unit)}."]
        if adjective:
            sentences.append(f"Its temporal behaviour is {adjective}.")
        return sentences
    prefix = f"A ~{frequency} Hz {adjective + ' ' if adjective else ''}"
    consistent_with = ""
    if type_code == oc.TYPE_ELECTROMECHANICAL and level == oc.LEVEL_PROBABLE:
        lead = f"{prefix}electromechanical oscillation {where}."
    elif type_code == oc.TYPE_ELECTROMECHANICAL and single:
        lead = f"{prefix}oscillation {where}."
        consistent_with = "Available evidence is consistent with an electromechanical oscillation."
    elif type_code == oc.TYPE_ELECTROMECHANICAL:
        lead = f"{prefix}oscillation, possibly electromechanical, {where}."
    else:
        lead = f"{prefix}oscillatory component {where}."
    sentences = [lead] + ([consistent_with] if consistent_with else [])
    if behaviour == oc.BEHAVIOUR_GROWING:
        sentences.append("Its amplitude is increasing over the fitted interval.")
    if behaviour == oc.BEHAVIOUR_INCONSISTENT:
        sentences.append("Damping behaviour differs between the signals, so no single behaviour is reported for the component.")
    return sentences


def _corroboration(component: dict, cross: dict) -> str | None:
    if component["signal_count"] < 2:
        return None
    signals, distinct, recordings, overlap = cross["signals"], cross["distinct_measurements"], cross["recordings"], cross["overlap_s"] > 0
    if distinct < signals:
        return "These signals share source measurements, so they are not independent corroboration."
    if recordings >= 2:
        return f"The component is corroborated across {_word(recordings)} recordings" + (" with overlapping activity." if overlap else ", but the active intervals do not overlap.")
    return "The component is observed within one recording" + (" with overlapping activity." if overlap else ", and the active intervals do not overlap.")


def _unresolved_reason(mode: dict, coherence: dict, mode_facts: dict, coherence_facts: dict) -> str:
    missing = [name for name, layer in (("relative-phase", mode), ("coherence", coherence)) if layer["status"] == UNAVAILABLE]
    codes = (mode_facts["reason_codes"] if mode["status"] == UNAVAILABLE else []) + (coherence_facts["reason_codes"] if coherence["status"] == UNAVAILABLE else [])
    if not (mode_facts["computed"] and coherence_facts["computed"]):
        return "the spatial evidence was not computed for this comparison"
    if mode_facts["pattern"] == "shared_provenance":
        return "the signals share one source measurement, so they provide no independent spatial evidence"
    if not missing:
        return "the available spatial evidence does not separate the two readings"
    joined = " and ".join(missing)
    if codes and all(code in _SHORT_INTERVAL_CODES for code in codes):
        return f"the shared active interval is too short for reliable {joined} estimation"
    return f"{joined} evidence is unavailable for this event"


def _mechanism(component: dict, interpretation: dict, layers: dict, facts: dict) -> str | None:
    type_code = interpretation["probable_type"]["code"]
    if type_code == oc.TYPE_FORCED_SUSTAINED:
        return "Sustained oscillatory behaviour is present; the forcing source is not identified."
    if type_code == oc.TYPE_CONTROL_CONVERTER:
        return "A control or converter interaction is possible, but no plant or controller metadata is available to identify a mechanism."
    if type_code == oc.TYPE_SUB_SYNCHRONOUS:
        return "A sub-synchronous mechanism is possible on the combined evidence but is not confirmed."
    if type_code == oc.TYPE_UNRESOLVED:
        if any(d["code"] == oc.DESCRIPTOR_HIGHER_FREQUENCY for d in interpretation.get("descriptors", [])):
            return "Available evidence is insufficient to identify a control, converter or sub-synchronous mechanism."
        return "The available evidence does not identify a mechanism."
    if type_code != oc.TYPE_ELECTROMECHANICAL:
        return None
    if component["signal_count"] < 2:
        return "Cross-signal modal evidence is not available, so the local/inter-area subtype cannot be determined."
    strength = (interpretation.get("interpretation_strength") or {}).get("code")
    pattern = facts["mode_shape"]["pattern"]
    coherence = layers["coherence"]
    if not facts["mode_shape"]["computed"]:
        # The DEC-179 reading (no synchronization context): a subtype rests on frequency, recordings and activity alone.
        if interpretation["probable_type"].get("subtype"):
            return ("Frequency, recordings and overlapping activity are compatible with an inter-area reading, which remains provisional because "
                    "relative-phase and coherence evidence were not computed for this comparison.")
        return "Local versus inter-area behaviour remains unresolved because the spatial evidence was not computed for this comparison."
    if strength == oi.STRENGTH_SUPPORTED:
        return ("Stable spatial phase separation and clear same-variable coherence support a provisional inter-area interpretation; the available metadata "
                "does not independently prove that the measurements represent separate grid areas.")
    if interpretation["probable_type"].get("subtype"):
        why = {UNAVAILABLE: "coherence is unavailable", CAUTION: "coherence is weak or marginal"}.get(coherence["status"], "the available metadata does not establish separate grid areas")
        return f"Stable phase separation across distinct measurements is consistent with an inter-area interpretation, which remains provisional because {why}."
    if pattern == "in_phase":
        return ("Distinct measurements respond approximately in phase, a coherent response that does not distinguish between local and inter-area behaviour; "
                "the subtype remains unresolved.")
    if pattern == "unstable":
        return "The relative phase is not stable across the common interval, so local versus inter-area behaviour remains unresolved."
    if pattern in ("anti_phase", "intermediate", "mixed"):
        return ("Phase separation is present, but the frequency, recording or activity conditions do not support an inter-area reading by themselves; "
                "local versus inter-area behaviour remains unresolved.")
    return "Local versus inter-area behaviour remains unresolved because " + _unresolved_reason(
        layers["mode_shape"], coherence, facts["mode_shape"], facts["coherence"]) + "."


def _caution(interpretation: dict) -> str | None:
    for item in interpretation.get("contradictory_evidence", []):
        return item["message"]
    for item in interpretation.get("limiting_evidence", []):
        if item["code"] in ("derived_from_same_source", "spatial_evidence_shared_provenance", "no_temporal_overlap"):
            return item["message"]
    return None


# ---------------------------------------------------------------- public
def build_component_summary(
    component: dict, *, units_by_index: dict[int, str | None], integrated: bool, mode_shape: dict | None = None, coherence: dict | None = None,
) -> dict:
    """The summary of one interpreted component (``component["interpretation"]`` must exist). Reads structured results only."""
    interpretation = component["interpretation"]
    unit = _units(component, units_by_index)
    cross, cross_facts = _cross_signal_layer(component)
    damping, damping_facts = _damping_layer(component)
    mode, mode_facts = _mode_shape_layer(component, integrated, mode_shape)
    coh, coh_facts = _coherence_layer(component, integrated, coherence, mode_facts["chosen"])
    layers = {"mode_shape": mode, "coherence": coh}
    facts = {"mode_shape": mode_facts, "coherence": coh_facts}
    sentences = _lead(component, interpretation, unit)
    for extra in (_corroboration(component, cross_facts), _mechanism(component, interpretation, layers, facts)):
        if extra:
            sentences.append(extra)
    probable, subtype = interpretation["probable_type"], interpretation["probable_type"].get("subtype")
    strength = interpretation.get("interpretation_strength")
    observed = f"{_plural(component['signal_count'], 'signal')} · {_plural(component['distinct_measurement_count'], 'distinct measurement')}"
    observed += f" · {_plural(component['recording_count'], 'recording')}"
    fields = [
        {"code": "behaviour", "label": "Behaviour", "value": interpretation["behaviour_classification"]["label"]},
        {"code": "type", "label": "Oscillation type", "value": probable["label"]},
    ]
    if subtype:
        fields.append({"code": "subtype", "label": "Subtype", "value": subtype["label"]})
    if strength:
        fields.append({"code": "strength", "label": "Interpretation strength", "value": strength["label"]})
    fields.append({"code": "observed", "label": "Observed in", "value": observed})
    return {
        "component_id": component["id"],
        "title": f"Component around {_hz(component['representative_frequency_hz'])} Hz",
        "frequency_hz": component["representative_frequency_hz"],
        "growing": interpretation["behaviour_classification"]["code"] == oc.BEHAVIOUR_GROWING,
        "fields": fields,
        "evidence": [_spectrum_layer(component), _time_frequency_layer(component), damping, cross, mode, coh],
        "conclusion": " ".join(sentences),
        "caution": _caution(interpretation),
    }
