def test_collision_comparison_formula_is_symmetric():
    """The formula used to compute the other-calc raw label must be structurally
    identical to the formula used for the current calc.  If calc A and calc B share
    the same (displayGlyph, sourceName, first-V-channel), both will detect the collision and
    return null — no unilateral compact label survives.
    Covers scenario 1 (same-bay V-channel collision) and scenario 2 (shared V-channel
    across different feeder-current calcs).
    """
    source = _source()
    body = _compact_label_body(source)
    # Current-calc raw label uses WW_POWER_DISPLAY_GLYPHS (via displayGlyph):
    assert 'displayGlyph + " · " + inv.sourceName + " · " + wwChannelDisplayName(v1.source_id, v1.channel_name)' in body
    # Other-calc label formula used in the collision comparison uses WW_POWER_DISPLAY_GLYPHS too:
    assert (
        'WW_POWER_DISPLAY_GLYPHS[other.operation] + " · " + oinv.sourceName + " · " + '
        "wwChannelDisplayName(ov1.source_id, ov1.channel_name)"
    ) in body


def test_raw_label_uses_only_first_voltage_channel_name():
    """The compact label is built from the FIRST input (voltage channel) only.
    Two power calcs that share the same first voltage channel but differ in their
    current channels — e.g. P(VA·IA) and P(VA·IB) — therefore produce the same raw
    string.  The collision check then detects this and returns null for both,
    preventing identical compact labels for distinguishable calculated channels.
    Covers scenario 2 (shared busbar voltage, different feeder currents).
    """
    source = _source()
    body = _compact_label_body(source)
    # The raw string is built once, from displayGlyph + v1 (first input) only.
    raw_pos = body.index("const raw = ")
    raw_line_end = body.index("\n", raw_pos)
    raw_line = body[raw_pos:raw_line_end]
    # Display glyph and v1 (first input) contribute to the label:
    assert "displayGlyph" in raw_line
    assert "v1.source_id" in raw_line
    assert "v1.channel_name" in raw_line
    # No second-input channel (v2 / inputs[1]) contributes to the raw label:
    assert "v2" not in raw_line
    assert "inputs[1]" not in raw_line


def test_different_first_voltage_channels_produce_distinguishable_labels():
    """Two power calcs from the same recording that use DIFFERENT first voltage
    channel names (e.g. different bays: Bay1-VA vs Bay2-VA) will produce distinct
    raw labels.  The collision check will NOT fire; both receive compact labels that
    distinguish them without falling back to the canonical name.
    Covers scenario 1 (different bays, unique per-bay voltage channel names).
    """
    source = _source()
    body = _compact_label_body(source)
    # The raw label is the concatenation of displayGlyph, sourceName, and the DISPLAY NAME
    # of the first input channel.  A different channel_name in v1 means a different
    # display-name call argument, hence a different raw string.
    raw_pos = body.index("const raw = ")
    raw_line_end = body.index("\n", raw_pos)
    raw_line = body[raw_pos:raw_line_end]
    assert "wwChannelDisplayName(v1.source_id, v1.channel_name)" in raw_line


def test_user_entered_output_name_suppresses_compact_label():
    """The compact label is suppressed whenever calc.name does not exactly match
    the autogenerated canonical name.  The shared helper wwCcPowerCanonicalName
    is used so both wwPowerCompactLabel and wwCcComputeSuggestedName stay in sync
    (DEC-208/DEC-202).  A user-entered name like 'P (custom)' fails the guard.
    """
    source = _source()
    body = _compact_label_body(source)
    # Guard must delegate to the shared helper.
    assert "const expectedName = wwCcPowerCanonicalName(calc.operation, calc.inputs);" in body, \
        "guard must use wwCcPowerCanonicalName helper"
    guard_snippet = "if (!expectedName || calc.name !== expectedName) return null;"
    assert guard_snippet in body, "exact-match guard missing from wwPowerCompactLabel"
    # Guard must appear after the inputs check (v1) and before the inventory lookup.
    v1_pos = body.index("const v1 = ")
    guard_pos = body.index("const expectedName = ")
    inv_pos = body.index("const inv = ")
    assert v1_pos < guard_pos < inv_pos, (
        "exact-match guard must come after inputs check and before inventory lookup"
    )


def test_user_name_starting_with_glyph_paren_suppresses_compact_label():
    """Regression: a user-entered name such as 'P (my custom name)' starts with
    the glyph + '(' prefix.  The old startsWith guard would have allowed compact
    label generation for such a name.  The new exact-match guard must not, because
    'P (my custom name)' !== 'P (VA, IA)' (the canonical autogenerated name from
    wwCcPowerCanonicalName).
    """
    source = _source()
    body = _compact_label_body(source)
    # Must NOT use startsWith — the old, too-broad guard.
    assert 'calc.name.startsWith(glyph + " (")' not in body, (
        "old startsWith guard must be replaced with exact-match guard"
    )
    # Must use strict inequality against the shared helper result.
    assert "if (!expectedName || calc.name !== expectedName) return null;" in body
