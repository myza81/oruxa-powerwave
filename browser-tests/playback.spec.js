// channels, 50 Hz, a DELIBERATELY long-for-a-test-fixture 4-second
// duration -- long enough that "wait a short real interval, assert
// playback advanced but has not yet completed" is reliable, unlike the
// pre-existing ~10-40ms smoke-test fixtures. `synth_playback_b` carries a
// different (non-overlapping) recording start date so it forms its own,
// SEPARATE Time Group from `synth_playback` when both are loaded into one
// workspace.
//
// Assertions stay at the "did it move / did it stop / did it respond"
// level throughout (no exact frame-count or pixel-delta assertions,
// matching the existing smoke test's own established philosophy) --
// timing-sensitive real-browser behavior is inherently non-deterministic
// down to the millisecond.

const { test, expect } = require("@playwright/test");
